--
-- ★ 지금 이 컬럼을 **쓰는 코드는 없다**
-- ---------------------------------------------------------------------------
-- 저장소 전수 확인 결과:
--     쓰기   `storage/database.py:UPSERT_SQL` 의 컬럼 목록에 filed_date 가 없다.
--            `migrate_execute.py` 는 `auction_case` 에 넣지만 값은 리터럴 NULL 이다.
--            -> **auction.filed_date 를 채우는 현행 코드는 0곳이다.**
--     읽기   `api/v1/item.py` 와 `src/app/properties/[id]/page.tsx` 는
--            `auction_case.filed_date`(별개 컬럼)를 읽어 상세 화면에 그린다.
--
-- 즉 313개 값은 **지금은 없어진 어떤 처리**가 남긴 것이다(028 을 만든 그 변경과 함께
-- 사라진 것으로 보인다). 그래도 컬럼을 **되살린다**:
--   1. 라이브에 실데이터 313건이 들어 있다. 스키마를 맞춰 놓지 않으면 새 배포와
--      운영 DB 가 계속 어긋나고, 그 어긋남이 이번처럼 조용히 쌓인다.
--   2. 나중에 채우는 쪽이 돌아왔을 때 컬럼이 있어야 한다.
--   3. 지우는 쪽으로 맞추면 실데이터 313건이 사라진다 — 되돌릴 수 없다.
-- 값을 채우는 일은 이 파일이 하지 않는다(025 가 backfill 을 분리한 것과 같은 관례).
--
-- 안전성
-- ---------------------------------------------------------------------------
-- `ALTER TABLE ... ADD COLUMN` 은 기존 행을 건드리지 않는다(전부 NULL 로 시작).
-- `UPSERT_SQL` 의 SET 목록에 없으므로 매일 크롤이 이 값을 덮어쓰지 않는다 —
-- 실제로 313행은 2026-09-01 크롤(updated_at 갱신)을 지나고도 값이 남아 있다.
--
-- ★ SQLite 는 `ADD COLUMN` 에 IF NOT EXISTS 가 없다. 이미 있으면 러너가 예외로 죽는데,
--   러너는 파일명으로 적용 여부를 판단하므로 정상 경로에서는 두 번 실행되지 않는다
--   (라이브는 이미 이 이름이 이력에 있어 SKIP 된다). 025 와 같은 조건이다.

ALTER TABLE auction ADD COLUMN filed_date TEXT;
