-- 031_add_recent_items_first_viewed_at.sql
-- "처음 본 시각"을 남긴다 — Time-to-Decision 의 시작점 (2026-09-04)
--
-- 왜 필요한가 — 지금 구조로는 T2D 를 **잴 수 없다**
-- ---------------------------------------------------------------------------
-- 콕찰의 핵심 KPI 후보는 Time to Decision 이다:
--
--     물건을 **처음** 발견한 시점  ->  입찰 여부를 판단한 시점
--
-- 그런데 `recent_items.viewed_at` 은 그 시작점이 될 수 없다. 두 가지 이유가 있고
-- 둘 다 의도된 동작이라 그 자체는 결함이 아니다:
--
--   1. 재조회마다 **덮어쓴다**
--      `api/v1/recent_items.py`: `ON CONFLICT(user_id,item_id) DO UPDATE SET viewed_at = ?`
--      즉 이 값은 "마지막으로 본 시각"이다. 같은 물건을 다시 보면 시작점이 앞으로
--      끌려와, 오래 고민한 물건일수록 T2D 가 **짧게** 나온다(정반대로 틀린다).
--
--   2. 20건으로 **잘린다**
--      같은 파일이 `RECENT_ITEMS_DISPLAY_LIMIT` 밖의 행을 DELETE 한다. 물건을 많이
--      보는 사용자일수록 처음 본 기록이 먼저 사라진다.
--
-- 그래서 **덮어쓰지 않는 열**을 따로 둔다. `viewed_at` 의 의미는 그대로 두고
-- (화면의 "최근 본 물건" 정렬이 그 값을 쓴다), 시작점만 별도로 보관한다.
--
-- ★ 20건 잘림은 이 마이그레이션이 고치지 않는다
-- ---------------------------------------------------------------------------
-- 행 자체가 지워지면 열이 있어도 소용없다. 보존 정책을 바꾸는 것은 저장 비용과
-- 사용자에게 보이는 목록 길이에 대한 **제품 결정**이라 여기서 정하지 않는다.
-- `audit_time_to_decision.py` 가 그 한계를 측정할 때마다 함께 보고한다 —
-- 측정값이 어느 범위에서만 참인지 모르면 그 숫자가 더 위험하다.
--
-- ★ 이 파일은 **순수 가산**이다 — `ADD COLUMN` 하나뿐이고 기존 값을 건드리지 않는다.
--   기존 행은 NULL 로 시작한다(= "언제 처음 봤는지 모른다"). 그 상태를 감사기가
--   "모름"으로 정확히 세지, 0 이나 지금 시각으로 메우지 않는다.
--   **운영 적용 자체는 승인 영역이다**(`docs/CLAUDE.md`).
--
-- ★ SQLite 는 `ADD COLUMN` 에 IF NOT EXISTS 가 없다. 러너는 파일명으로 적용 여부를
--   판단하므로 정상 경로에서는 두 번 실행되지 않는다(025/028 과 같은 조건).

ALTER TABLE recent_items ADD COLUMN first_viewed_at TEXT;
