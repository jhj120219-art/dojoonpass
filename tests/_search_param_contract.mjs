// 파라미터를 조용히 무시하므로, 값이 실리는 순간 "조건을 걸었는데 전체 결과가 나오는"
// 상태가 된다(BUGS #123 이 실제로 그랬다). 지금은 해당 UI 가 "준비 중입니다"
// 자리표시자라 값이 실릴 수 없어 무해하다.
//
// 항목을 뺄 때
// -----------------------------------------------------------------
// 구현되면 **반드시** 여기서 뺀다. 빼지 않으면 그 파라미터가 다시 깨져도 두 검사가
// 모두 눈감는다. 양쪽 파일의 "죽은 예외 금지" 검사가 그것을 강제한다.
